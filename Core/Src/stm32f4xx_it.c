/**
  * @brief This function handles SDIO global interrupt.
  */
void SDIO_IRQHandler(void)
{
  /* USER CODE BEGIN SDIO_IRQn 0 */
  /* TEAM CODE (integration: Brendon): skip the HAL SDIO handler when no HAL transfer owns the bus (SD card fix) */
  /* SDIO = the MCU's SD-card interface. Its interrupt reports the end of a
   * data transfer (DATAEND) and data errors (bad CRC, timeout). Only while a
   * HAL interrupt or DMA transfer is running (hsd.Context says so) may
   * HAL_SD_IRQHandler act on it; outside one it would send CMD12 ("stop")
   * to an idle card, or clear the DATAEND flag a polled USB-MSC read is
   * waiting for. So the hook masks the SDIO interrupts and returns 1, and the
   * HAL handler is skipped. Full story: Core/Src/sd_detect_override.c. */
  if (SD_SdioIrqPrehook() != 0U)
  {
    return;   /* no HAL IT/DMA transfer owns the SDIO: keep HAL_SD_IRQHandler off the bus */
  }
  /* USER CODE END SDIO_IRQn 0 */
  HAL_SD_IRQHandler(&hsd);
  /* USER CODE BEGIN SDIO_IRQn 1 */

  /* USER CODE END SDIO_IRQn 1 */
}

