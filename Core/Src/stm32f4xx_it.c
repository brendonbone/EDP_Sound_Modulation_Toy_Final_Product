/**
  * @brief This function handles DMA2 stream3 global interrupt.
  */
void DMA2_Stream3_IRQHandler(void)
{
  /* USER CODE BEGIN DMA2_Stream3_IRQn 0 */
  /* TEAM CODE (integration: Brendon): SD receive-DMA hook that must run before the HAL clears TCIF (SD card fix) */
  /* DMA2 Stream3 copies what the SD card sends (reads) from the SDIO into
   * RAM; Stream6 does writes and needs no hook. Its transfer-complete
   * interrupt (TCIF) can come a few microseconds BEFORE the SDIO has checked
   * the CRC of the last block. The hook waits for that verdict, keeps a CRC
   * error so the read fails as it should, and clears DTEN (the SDIO's
   * "start data transfer" bit), so the HAL's next write to that register
   * cannot start a "ghost" receive that no card feeds. Full story:
   * sd_detect_override.c. */
  SD_RxDmaIrqPrehook();   /* must run before the HAL clears TCIF: stops the HAL re-arming the SDIO data path */
  /* USER CODE END DMA2_Stream3_IRQn 0 */
  HAL_DMA_IRQHandler(&hdma_sdio_rx);
  /* USER CODE BEGIN DMA2_Stream3_IRQn 1 */

  /* USER CODE END DMA2_Stream3_IRQn 1 */
}

