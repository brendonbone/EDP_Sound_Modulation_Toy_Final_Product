/* TEAM CODE (owner: Jack): I2S2 microphone DMA callbacks for JackAudioTask (written by Brendon in the PD6 port) */
/* I2S2 RX DMA (JackAudioTask owns it): half/full -> thread flags. The task
 * treats both bits pending at once as a missed deadline (slide 9). */
/* Both run in DMA1_Stream3_IRQHandler (priority 5) through HAL_DMA_IRQHandler.
 * I2S is a serial audio bus; here I2S2 clocks the PDM microphone (PB10 clock,
 * PB15 data). PDM = pulse density modulation: the mic sends a 1-bit stream,
 * which JackAudioTask's PDM2PCM filter turns into normal 16-bit samples
 * (PCM). DMA = direct memory access: hardware that copies the bits into
 * s_pdm_buffer (jack_audio_sd.c) without the CPU, round and round (circular):
 *   half-transfer     -> JACK_AUDIO_HALF_FLAG: the first half is full;
 *   transfer-complete -> JACK_AUDIO_FULL_FLAG: the second half is full.
 * Each half is about 1 ms of microphone bits (32 PCM samples). The task
 * converts the full half while the DMA fills the other one.
 * Where 1 ms and 32 come from: I2S2 is set to 64 kHz with 32-bit frames, so
 * the mic gets a clock of about 2 MHz and sends that many bits a second. A
 * half holds 128 x 16 = 2048 bits (about 1 ms); the filter keeps one sample
 * per 64 bits (decimation by 64), so 32 samples: audio at 32 kHz. */
void HAL_I2S_RxHalfCpltCallback(I2S_HandleTypeDef *hi2s)
{
    if (hi2s->Instance == SPI2 && JackAudioTaskHandle != NULL) {
        (void)osThreadFlagsSet(JackAudioTaskHandle, JACK_AUDIO_HALF_FLAG);
    }
}
void HAL_I2S_RxCpltCallback(I2S_HandleTypeDef *hi2s)
{
    if (hi2s->Instance == SPI2 && JackAudioTaskHandle != NULL) {
        (void)osThreadFlagsSet(JackAudioTaskHandle, JACK_AUDIO_FULL_FLAG);
    }
}

