/* ---- HSE source probe -------------------------------------------------------
 * HSE = the high-speed external clock input (pins OSC_IN / OSC_OUT); the PLL
 * turns its 8 MHz into the 72 MHz CPU clock (SystemClock_Config).
 * The .ioc is set up for the PCB: HSE = 8 MHz crystal (RCC_HSE_ON in
 * SystemClock_Config). The Nucleo-F411RE the team also tests on has no crystal
 * fitted; its 8 MHz comes from the ST-LINK MCO into OSC_IN, which needs BYPASS.
 * Rather than keeping two builds, probe before SystemClock_Config() runs:
 *   1) BYPASS (amplifier off, OSC_IN driven externally). This is the
 *      configuration every board test so far ran on. A passive crystal cannot
 *      produce a clock with the amplifier off, so on the PCB HSERDY stays 0.
 *   2) otherwise crystal mode (HSEBYP cleared).
 * Bypass is tried first because the reverse order is ambiguous: an MCO-driven
 * OSC_IN can also satisfy the crystal-mode amplifier. HAL_RCC_OscConfig() with
 * RCC_HSE_ON only sets HSEON and leaves HSEBYP as the probe left it, so the
 * generated code then brings the PLL up from whichever source started. Costs
 * at most HSE_STARTUP_TIMEOUT (100 ms) once, on the crystal board. */
static uint8_t hse_ready_within(uint32_t timeout_ms)
{
    uint32_t t0 = HAL_GetTick();
    while (READ_BIT(RCC->CR, RCC_CR_HSERDY) == 0U)
    {
        if ((HAL_GetTick() - t0) > timeout_ms)
        {
            return 0U;
        }
    }
    return 1U;
}

static void clock_probe_hse(void)
{
    /* 1) external clock on OSC_IN (Nucleo ST-LINK MCO) */
    CLEAR_BIT(RCC->CR, RCC_CR_HSEON);
    SET_BIT(RCC->CR, RCC_CR_HSEBYP);
    SET_BIT(RCC->CR, RCC_CR_HSEON);
    if (hse_ready_within(HSE_STARTUP_TIMEOUT))
    {
        return;   /* Nucleo: leave bypass mode set for SystemClock_Config() */
    }

    /* 2) crystal (PCB). HSEBYP may only change while HSE is off. */
    CLEAR_BIT(RCC->CR, RCC_CR_HSEON);
    while (READ_BIT(RCC->CR, RCC_CR_HSERDY) != 0U) { }
    CLEAR_BIT(RCC->CR, RCC_CR_HSEBYP);
    SET_BIT(RCC->CR, RCC_CR_HSEON);
    (void)hse_ready_within(HSE_STARTUP_TIMEOUT);   /* SystemClock_Config() re-checks; Error_Handler() if neither */
}

/* ---- HAL callbacks (ISR context). Rule: only flags, timeout-0 queue puts,
 * semaphore releases and pointer bookkeeping happen here — no text
 * formatting, no memcpy of audio (lecture 07). All IRQs that reach these run
 * at NVIC priority >= 5 (configLIBRARY_MAX_SYSCALL_INTERRUPT_PRIORITY). ---- */
/* ISR = interrupt service routine: the code the CPU runs when an interrupt
 * fires. The path is always the same: the peripheral's IRQ handler
 * (stm32f4xx_it.c) calls the HAL, the HAL calls one of the callbacks below,
 * and the callback sets a thread flag on the task that owns the peripheral.
 * That task wakes up in osThreadFlagsWait and does the real work at its own
 * priority. Why the callbacks do so little:
 *   - an ISR is not a task and can never wait, so a queue put from an ISR
 *     must use timeout 0 (the CMSIS-RTOS layer refuses any other timeout
 *     there); a full queue drops the item and counts it (slide 18);
 *   - while an ISR runs, every task and every less urgent interrupt waits,
 *     so it must be short: no text formatting (slow, and it needs a lot of
 *     stack) and no copying of audio;
 *   - handing over costs nothing: if the woken task outranks the one that
 *     was interrupted, FreeRTOS switches to it as soon as the ISR ends.
 * Why priority 5 or more: in the NVIC (the Cortex-M4's interrupt controller)
 * a LOWER number is MORE urgent (0..15 here). Inside its critical sections
 * FreeRTOS masks only priorities 5..15 (configMAX_SYSCALL_INTERRUPT_PRIORITY
 * in FreeRTOSConfig.h: the same 5, shifted into the NVIC register format),
 * so only those interrupts may call the FreeRTOS "FromISR" functions behind
 * osThreadFlagsSet and osMessageQueuePut. An interrupt at 0..4 could cut
 * into the kernel half-way through a change to its task lists and corrupt
 * them. Here (.ioc): the four DMA streams and SDIO at 5; OTG_FS (USB) at 6;
 * TIM5 (the HAL tick) and FreeRTOS's own SysTick and PendSV at 15.
 * Slide numbers in this file refer to ZEIT4230 lecture 07. "PD6" below is
 * the team's Prototype Design 6 stage, in which each member's code was moved
 * into its own FreeRTOS task (notes in the docs/pr folder). */

